HERE = Path(__file__).resolve().parent
WORK = Path("renovate-agent-work").resolve()

AUTO_MERGE_TYPES = ("patch", "minor", "digest", "lockfile")  # what the model may call safe
BATCH = 6  # PRs per Claude run; each run has its own budget
MAX_MERGES_PER_REPO = 10  # per run
MAX_MERGES = 40  # per run, all repos
# No new merge starts later than this after the run began, so the last one is still
# watched (up to 90 min settle + soak) before the job timeout (23 h) kills the run.
MERGE_WINDOW = 20 * 60 * 60
STARTED = time.monotonic()
MAX_FIX_ATTEMPTS = 2  # fix commits per PR before it needs a human
MAX_FIXES = 20
MAX_FIX_LINES = 400  # changed lines in the source files, lockfiles not counted
CI_WAIT = 30 * 60  # seconds to wait for CI on fix commits before merging what is ready
DEFAULT_SETTLE_MINUTES = 30  # CI on the merged commit plus the GitImage rollout
NO_CI_GRACE = 5 * 60  # no checks on the merged commit after this long: it has no push CI
SOAK = 5 * 60  # seconds the rollout must then stay up
POLL = 30
LOG_LINES = 150  # tail of each failed CI job's log shown to the model
MARKER = "<!-- renovate-agent:verdict"
FIX_AUTHOR = "renovate-agent"
ZERO_WIDTH_SPACE = chr(0x200B)

# The agent's whole reach: read the checkouts and the PR files this script wrote, read
# release notes and API docs, read cluster state. No Edit/Write, no arbitrary shell, no gh;
# in --print mode anything not listed is denied.
ALLOWED_TOOLS = [
    "Read",
    "Grep",
    "Glob",
    "Bash(kubectl get *)",
    "WebFetch(domain:github.com)",
    "WebFetch(domain:api.github.com)",
    "WebFetch(domain:raw.githubusercontent.com)",
    "WebFetch(domain:docs.rs)",
    "WebFetch(domain:crates.io)",
    "WebFetch(domain:www.npmjs.com)",
    "WebFetch(domain:registry.npmjs.org)",
]

# Files a fix may touch: source and manifests. Everything that runs at build time or in CI
# (workflows, Dockerfiles, build scripts, cargo config), decides what is checked
# (deny.toml), or deploys (charts) is out, and lockfiles are regenerated by this script.
FIX_SUFFIXES = (
    ".rs", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".vue", ".svelte",
    ".css", ".scss", ".html", ".toml", ".json",
)  # fmt: skip
FIX_DENY = re.compile(
    r"(^|/)\.|(^|/)(Dockerfile[^/]*|build\.rs|deny\.toml|rust-toolchain(\.toml)?|"
    r"Cargo\.lock|package-lock\.json|Chart\.yaml|values[^/]*\.yaml)$|"
    r"(^|/)(charts|helm|node_modules|target|vendor)/"
)


def gh(*args: str) -> str:
    return subprocess.run(["gh", *args], check=True, capture_output=True, text=True).stdout


def git(*args: str, cwd: str | Path = ".", push: bool = False) -> str:
    """Run git. With push=True the GitHub token is passed, through the environment so it
    cannot end up in an error message that quotes the command."""
    env = dict(os.environ, GIT_AUTHOR_NAME=FIX_AUTHOR, GIT_COMMITTER_NAME=FIX_AUTHOR)
    env["GIT_AUTHOR_EMAIL"] = env["GIT_COMMITTER_EMAIL"] = f"{FIX_AUTHOR}@users.noreply.github.com"
    if push:
        token = base64.b64encode(f"x-access-token:{os.environ['GH_TOKEN']}".encode()).decode()
        env.update(GIT_CONFIG_COUNT="1", GIT_CONFIG_KEY_0="http.extraheader", GIT_CONFIG_VALUE_0=f"AUTHORIZATION: basic {token}")
    return subprocess.run(["git", *args], check=True, cwd=cwd, env=env, capture_output=True, text=True).stdout


def flag(name: str) -> bool:
    return os.environ.get(name, "").lower() == "true"


def one_line(text: str, limit: int = 300) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= limit else text[: limit - 1] + "…"


def summary(text: str) -> None:
    """Show text on the workflow run page (and in the log)."""
    print(text, flush=True)
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    if path:
        with open(path, "a") as f:
            f.write(text + "\n")


def clean_env() -> dict:
    """The environment without credentials, for Claude and for cargo/npm. TOKEN catches
    GH_TOKEN, KEY the nix cache's AWS keys the runner's hook template injects."""
    secret = re.compile(r"TOKEN|SECRET|PASSWORD|KEY|CREDENTIAL", re.IGNORECASE)
    return {k: v for k, v in os.environ.items() if not secret.search(k)}


class Repo:
    """One entry of repos.yaml, with the state of a run."""

    def __init__(self, entry: dict, login: str):
        self.name = entry["repo"]
        self.owner = self.name.split("/")[0].lower()
        self.login = login  # the token's user: Renovate's PRs and our comments are by it
        self.gitimage = entry.get("gitimage")
        self.settle = int(entry.get("settle_minutes", DEFAULT_SETTLE_MINUTES)) * 60
        lines = (HERE / "denylist.txt").read_text().splitlines() + list(entry.get("deny", []))
        self.deny = re.compile("|".join(line.strip() for line in lines if line.strip() and not line.startswith("#")))
        self.work = WORK / self.name.replace("/", "_")
        self.default_branch = ""
        self.known_revisions: dict[tuple[str, str], bool] = {}

    @property
    def url(self) -> str:
        return f"https://github.com/{self.name}.git"


# --- selecting PRs -----------------------------------------------------------------------


def title_key(title: str) -> str:
    """Identifies a verdict. The title carries the target version, so a rebase keeps the
    verdict and a newer version gets a fresh one."""
    return base64.b64encode(title.encode()).decode()


def is_renovate(repo: Repo, pr: dict) -> bool:
    """A renovate/* branch of this repo, opened by the owner's token (self-hosted Renovate
    runs with it). The repos are public: a fork PR that merely names its branch renovate/*
    must not count."""
    return (
        pr["headRefName"].startswith("renovate/")
        and not pr["isCrossRepository"]
        and not pr["isDraft"]
        and pr["author"]["login"].lower() in (repo.owner, repo.login.lower(), "renovate", "app/renovate")
    )


def ci_state(pr: dict) -> str:
    """passing, failing or pending. Passing needs at least one real CI check run, and
    includes Renovate's own statuses (stability-days for minimumReleaseAge, artifacts)."""
    checks = pr["statusCheckRollup"]

    def state(check: dict) -> str:
        if check["__typename"] == "StatusContext":
            return {"SUCCESS": "passing", "PENDING": "pending", "EXPECTED": "pending"}.get(check["state"], "failing")
        if check["status"] != "COMPLETED":
            return "pending"
        return "passing" if check["conclusion"] in ("SUCCESS", "SKIPPED", "NEUTRAL") else "failing"

    states = [state(c) for c in checks]
    if "failing" in states:
        return "failing"
    ran_ci = any(c["__typename"] == "CheckRun" and c.get("conclusion") == "SUCCESS" for c in checks)
    return "passing" if ran_ci and all(s == "passing" for s in states) else "pending"


def has_verdict(repo: Repo, pr: dict) -> bool:
    marker = f"{MARKER} key={title_key(pr['title'])} -->"
    return any(c["author"]["login"] == repo.login and marker in c["body"] for c in pr["comments"])


def list_prs(repo: Repo) -> list[dict]:
    fields = (
        "number,title,headRefName,headRefOid,author,isCrossRepository,isDraft,createdAt,"
        "files,statusCheckRollup,comments,labels,mergeable"
    )
    prs = json.loads(gh("pr", "list", "--repo", repo.name, "--state", "open", "--limit", "100", "--json", fields))
    only = os.environ.get("ONLY_PR", "")
    mine = [pr for pr in prs if is_renovate(repo, pr) and (not only or str(pr["number"]) == only)]
    return sorted(mine, key=lambda pr: pr["number"])


def labels(pr: dict) -> set[str]:
    return {label["name"] for label in pr["labels"]}


def needs_triage(repo: Repo, pr: dict) -> bool:
    """No verdict for the PR's current title yet, or CI fails on a PR called safe (a fix
    of ours that did not work, say). Removing the label also gets a PR triaged again."""
    verdict = labels(pr) & {"agent:safe", "agent:needs-human"}
    if not verdict or not has_verdict(repo, pr):
        return True
    if ci_state(pr) != "failing":
        return False
    # CI fails: a PR called safe gets another look, and so does one (a major, say) whose
    # head is a fix of ours that did not work, while it has fix attempts left.
    if "agent:safe" in verdict:
        return True
    head = json.loads(gh("api", f"repos/{repo.name}/commits/{pr['headRefOid']}"))
    return head["commit"]["author"]["name"] == FIX_AUTHOR and fix_attempts(repo, pr) < MAX_FIX_ATTEMPTS


def reverted_titles(repo: Repo) -> set[str]:
    """Titles of updates this agent merged and had to revert. Renovate reopens the same
    update after a revert; without this it would be merged and reverted every night."""
    merged = gh("pr", "list", "--repo", repo.name, "--state", "merged", "--label", "agent:reverted", "--json", "title")
    return {pr["title"] for pr in json.loads(merged)}


def never_auto_merge(repo: Repo, pr: dict, reverted: set[str]) -> str:
    """Why this PR needs a human whatever the model says, or '' if it does not."""
    if any(repo.deny.search(f["path"]) for f in pr["files"]):
        return "it touches a denylisted path (`agent/denylist.txt` in DiverOfDark/renovate-config)"
    if pr["title"] in reverted:
        return "the agent merged this same update before and had to revert it"
    return ""


def fix_attempts(repo: Repo, pr: dict) -> int:
    commits = json.loads(gh("api", f"repos/{repo.name}/pulls/{pr['number']}/commits?per_page=100"))
    return sum(1 for c in commits if c["commit"]["author"]["name"] == FIX_AUTHOR)


def select_prs(repo: Repo) -> list[dict]:
    reverted = reverted_titles(repo)
    selected = []
    for pr in list_prs(repo):
        if not (needs_triage(repo, pr) or flag("FORCE")):
            continue
        selected.append(
            {
                "number": pr["number"],
                "title": pr["title"],
                "branch": pr["headRefName"],
                "head": pr["headRefOid"],
                "opened": pr["createdAt"],
                "ci": ci_state(pr),
                "files": [f["path"] for f in pr["files"]],
                "never_auto_merge": never_auto_merge(repo, pr, reverted),
                "fix_attempts": fix_attempts(repo, pr),
                "renovate_comments": [
                    c["body"] for c in pr["comments"] if c["author"]["login"] == repo.login and "Artifact update problem" in c["body"]
                ],
            }
        )
    return selected


# --- preparing the model's input ---------------------------------------------------------


def strip_log(text: str) -> str:
    """CI log lines without the timestamps and colour codes."""
    text = re.sub(r"\x1b\[[0-9;]*[A-Za-z]", "", text)
    return "\n".join(re.sub(r"^\d{4}-\d\d-\d\dT[\d:.]+Z ", "", line) for line in text.splitlines())


def ci_failures(repo: Repo, sha: str) -> str:
    """The tail of the log of every failed GitHub Actions job on a commit."""
    runs = json.loads(gh("api", f"repos/{repo.name}/commits/{sha}/check-runs?per_page=100"))["check_runs"]
    parts = []
    for run in runs:
        if run["conclusion"] not in ("failure", "timed_out") or run.get("app", {}).get("slug") != "github-actions":
            continue
        try:
            log = gh("api", f"repos/{repo.name}/actions/jobs/{run['id']}/logs")
        except subprocess.CalledProcessError:
            log = "(log not available)"
        tail = "\n".join(strip_log(log).splitlines()[-LOG_LINES:])
        parts.append(f"## Failed check: {run['name']}\n\n```\n{tail}\n```")
    return "\n\n".join(parts)


def checkout_repo(repo: Repo) -> None:
    """Clone the default branch to <work>/main for the model to read."""
    if repo.work.exists():
        shutil.rmtree(repo.work)
    repo.work.mkdir(parents=True)
    info = json.loads(gh("repo", "view", repo.name, "--json", "defaultBranchRef"))
    repo.default_branch = info["defaultBranchRef"]["name"]
    git("clone", "--quiet", "--depth", "50", "--branch", repo.default_branch, repo.url, "main", cwd=repo.work)


def fetch_pr(repo: Repo, pr: dict) -> None:
    """Check the PR branch out for the model to read, and write its description, diff, CI
    failure logs and Renovate's artifact errors to a file."""
    number = str(pr["number"])
    tree = repo.work / f"pr-{number}"
    git("clone", "--quiet", "--depth", "50", "--branch", pr["branch"], repo.url, str(tree))
    body = json.loads(gh("pr", "view", number, "--repo", repo.name, "--json", "body"))["body"]
    diff = gh("pr", "diff", number, "--repo", repo.name)
    if len(diff) > 60000:
        diff = diff[:60000] + "\n… (diff cut at 60000 characters; read the checkout for the rest)"
    text = f"# {pr['title']}\n\n{body}\n\n# Diff\n\n```diff\n{diff}\n```\n"
    if pr["ci"] == "failing":
        text += f"\n# CI failures\n\n{ci_failures(repo, pr['head']) or 'No failed GitHub Actions job found (another check fails).'}\n"
    for comment in pr.pop("renovate_comments"):
        text += f"\n# Renovate comment\n\n{comment}\n"
    pr["checkout"] = f"pr-{number}"
    pr["file"] = f"pr-{number}.md"
    (repo.work / pr["file"]).write_text(text)


# --- running the model -------------------------------------------------------------------


def log_event(event: dict) -> None:
    """Print what Claude is doing, as it happens: its notes, each tool call, failed calls.

    Logging only: an event shape this does not know (they vary between CLI versions) is
    skipped, never fatal."""
    try:
        print_blocks(event)
    except (AttributeError, KeyError, TypeError):
        pass


def print_blocks(event: dict) -> None:
    message = event.get("message")
    blocks = message.get("content") if isinstance(message, dict) else None
    for block in blocks if isinstance(blocks, list) else []:
        if not isinstance(block, dict):
            continue
        kind = block.get("type")
        if kind == "text" and block["text"].strip():
            print(f"  claude: {one_line(block['text'])}", flush=True)
        elif kind == "thinking" and block["thinking"].strip():
            print(f"  claude (thinking): {one_line(block['thinking'], 200)}", flush=True)
        elif kind == "tool_use" and block["name"] == "StructuredOutput":
            print("  claude > writing the verdicts", flush=True)
        elif kind == "tool_use":
            args = ", ".join(f"{key}={one_line(value, 150)}" for key, value in block["input"].items())
            print(f"  claude > {block['name']}({args})", flush=True)
        elif kind == "tool_result" and block.get("is_error"):
            print(f"    failed: {one_line(str(block.get('content', '')), 200)}", flush=True)


def run_claude(repo: Repo, prs: list[dict]) -> list[dict]:
    listed = [{k: v for k, v in pr.items() if k != "head"} for pr in prs]
    prompt = (
        (HERE / "triage.md").read_text()
        + f"\n## Repository\n\n{repo.name}, default branch `{repo.default_branch}`"
        + (f", deployed by the GitImage `{repo.gitimage}` (namespace/name)" if repo.gitimage else ", not deployed from its default branch")
        + f".\n\nThe fix limit is {MAX_FIX_ATTEMPTS} attempts per PR.\n"
        + "\n## Pull requests to triage\n\n```json\n"
        + json.dumps(listed, indent=2)
        + "\n```\n"
    )
    command = [
        "claude",
        "--print",
        "--model", os.environ.get("RENOVATE_AGENT_MODEL") or "sonnet",
        "--max-budget-usd", os.environ.get("RENOVATE_AGENT_BUDGET_USD") or "5",
        "--allowedTools", *ALLOWED_TOOLS,
        "--json-schema", (HERE / "verdict.schema.json").read_text(),
        # One JSON event per line while it works, so the job log shows progress; the last
        # event is the result.
        "--output-format", "stream-json",
        "--verbose",
        # Ignore any Claude settings and MCP servers in the checkouts, so nothing in a repo
        # can widen the allowlist.
        "--setting-sources", "user",
        "--strict-mcp-config",
        "--no-session-persistence",
    ]  # fmt: skip
    env = clean_env()
    if os.environ.get("CLAUDE_CODE_OAUTH_TOKEN"):  # unset locally: Claude's own login
        env["CLAUDE_CODE_OAUTH_TOKEN"] = os.environ["CLAUDE_CODE_OAUTH_TOKEN"]
    print(f"claude: triaging {repo.name} {', '.join('#' + str(pr['number']) for pr in prs)}", flush=True)
    # The prompt goes in on stdin: after the variadic --allowedTools it would otherwise be
    # read as one more tool name. stderr goes straight to the job log.
    claude = subprocess.Popen(command, stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True, env=env, cwd=repo.work)
    claude.stdin.write(prompt)
    claude.stdin.close()
    result = {}
    for line in claude.stdout:
        try:
            event = json.loads(line)
        except json.JSONDecodeError:
            continue
        if event.get("type") == "result":
            result = event
        else:
            log_event(event)
    claude.wait()

    if result.get("is_error") or not isinstance((result.get("structured_output") or {}).get("verdicts"), list):
        summary(f"- {repo.name}: claude returned no verdicts (exit {claude.returncode}): {result.get('subtype')} {one_line(result.get('result'), 300)}")
        return []
    denied = [d.get("tool_name") for d in result.get("permission_denials", [])]
    print(f"claude: {result.get('num_turns')} turns, ${result.get('total_cost_usd', 0):.2f}, denied tool calls: {denied}")
    return result["structured_output"]["verdicts"]


# --- fixes -------------------------------------------------------------------------------


class FixError(Exception):
    pass


def cargo_deps(text: str) -> dict:
    """Every dependency of a Cargo.toml by section, and its [patch]/[replace] tables."""
    data = tomllib.loads(text)
    found = {}

    def walk(table: dict, prefix: str) -> None:
        for key in ("dependencies", "dev-dependencies", "build-dependencies"):
            for name, spec in (table.get(key) or {}).items():
                found[f"{prefix}{key}.{name}"] = spec
        for target, sub in (table.get("target") or {}).items():
            walk(sub, f"{prefix}target.{target}.")

    walk(data, "")
    walk(data.get("workspace") or {}, "workspace.")
    return {"deps": found, "patch": data.get("patch"), "replace": data.get("replace")}


def check_cargo(before: str, after: str) -> None:
    try:
        old, new = cargo_deps(before), cargo_deps(after)
    except tomllib.TOMLDecodeError as error:
        raise FixError(f"Cargo.toml would no longer be valid TOML: {one_line(error, 150)}") from None
    if new["patch"] != old["patch"] or new["replace"] != old["replace"]:
        raise FixError("a fix changes [patch] or [replace] in Cargo.toml")
    if added := set(new["deps"]) - set(old["deps"]):
        raise FixError(f"a fix adds dependencies: {', '.join(sorted(added))}")
    for key, spec in new["deps"].items():
        source = lambda s: {k: s.get(k) for k in ("git", "path", "registry", "branch", "rev", "tag", "package")} if isinstance(s, dict) else {}  # noqa: E731
        if source(spec) != source(old["deps"][key]):
            raise FixError(f"a fix changes where `{key}` comes from")


def check_package_json(before: str, after: str) -> None:
    try:
        old, new = json.loads(before), json.loads(after)
    except json.JSONDecodeError as error:
        raise FixError(f"package.json would no longer be valid JSON: {one_line(error, 150)}") from None
    for key in ("scripts", "overrides", "resolutions", "workspaces", "bin"):
        if old.get(key) != new.get(key):
            raise FixError(f"a fix changes `{key}` in package.json")
    for key in ("dependencies", "devDependencies", "peerDependencies", "optionalDependencies"):
        old_deps, new_deps = old.get(key) or {}, new.get(key) or {}
        if added := set(new_deps) - set(old_deps):
            raise FixError(f"a fix adds {key}: {', '.join(sorted(added))}")
        for name, version in new_deps.items():
            if re.search(r"[:/]", str(version)) and version != old_deps.get(name):
                raise FixError(f"a fix points `{name}` at a non-registry source")


def regenerate_lockfiles(tree: Path, manifests: set[str]) -> None:
    """Bring Cargo.lock / package-lock.json in line with edited manifests. Resolution only:
    `cargo metadata` and `npm install --package-lock-only --ignore-scripts` run no build or
    install scripts. Credentials are not in their environment."""
    for manifest in sorted(manifests):
        folder = (tree / manifest).parent
        if manifest.endswith("Cargo.toml"):
            root = next((d for d in [folder, *folder.parents] if (d / "Cargo.lock").exists() and tree in [d, *d.parents]), None)
            if root is None:
                continue
            command = ["cargo", "metadata", "--format-version", "1", "--manifest-path", str(root / "Cargo.toml")]
        elif (folder / "package-lock.json").exists():
            root = folder
            command = ["npm", "install", "--package-lock-only", "--ignore-scripts", "--no-audit", "--no-fund"]
        else:
            continue
        done = subprocess.run(command, cwd=root, env=clean_env(), capture_output=True, text=True)
        if done.returncode != 0:
            raise FixError(f"`{' '.join(command[:2])}` failed after the edits: {one_line(done.stderr[-800:], 600)}")


def apply_fixes(repo: Repo, pr: dict, fixes: list[dict]) -> str:
    """Apply the model's replacements to the PR branch, regenerate lockfiles and push.

    Returns the diff (lockfiles left out). The edits can be merged and deployed without
    review, so they are held to plain rules: existing source or manifest files only, never
    a denylisted path, each `find` text present exactly once, no new or re-pointed
    dependencies, a size limit. The personal token's push starts CI on the branch.
    """
    if len(fixes) > MAX_FIXES:
        raise FixError(f"{len(fixes)} edits, more than the {MAX_FIXES} allowed")
    tree = repo.work / pr["checkout"]
    git("checkout", "--force", pr["branch"], cwd=tree)  # drop anything left from before
    git("reset", "--hard", pr["head"], cwd=tree)
    manifests = set()

    for fix in fixes:
        path = fix["file"]
        target = tree / path
        if (
            os.path.normpath(path) != path
            or path.startswith(("/", ".."))
            or not path.endswith(FIX_SUFFIXES)
            or FIX_DENY.search(path)
            or repo.deny.search(path)
            or not target.is_file()
            or target.is_symlink()
            or tree.resolve() not in target.resolve().parents
        ):
            raise FixError(f"`{path}` is not a file the agent may edit")
        text = target.read_text()
        if text.count(fix["find"]) != 1:
            raise FixError(f"the text to replace occurs {text.count(fix['find'])} times in `{path}`, not once")
        new = text.replace(fix["find"], fix["replace"])
        if path.endswith("Cargo.toml"):
            check_cargo(text, new)
            manifests.add(path)
        elif path.endswith("package.json"):
            check_package_json(text, new)
            manifests.add(path)
        target.write_text(new)

    diff = git("diff", cwd=tree)
    if not diff:
        raise FixError("the edits change nothing")
    changed = sum(1 for line in diff.splitlines() if line[:1] in "+-" and line[:3] not in ("+++", "---"))
    if changed > MAX_FIX_LINES:
        raise FixError(f"the edits change {changed} lines, more than the {MAX_FIX_LINES} allowed")
    regenerate_lockfiles(tree, manifests)
    if not flag("DRY_RUN"):
        reasons = "\n".join(f"- {fix['file']}: {one_line(fix['reason'], 200)}" for fix in fixes)
        git("add", "--all", cwd=tree)
        git("commit", "--message", f"fix: adapt to {pr['title']}\n\n{reasons}", cwd=tree)
        git("push", repo.url, f"HEAD:refs/heads/{pr['branch']}", cwd=tree, push=True)
    return diff


# --- publishing --------------------------------------------------------------------------


def clean(text: str, limit: int) -> str:
    """Model output goes into a public comment: cap it, defuse @mentions and HTML comments,
    and make sure it cannot carry one of our credentials out."""
    for name in ("CLAUDE_CODE_OAUTH_TOKEN", "GH_TOKEN"):
        if os.environ.get(name):
            text = text.replace(os.environ[name], "[redacted]")
    return text[:limit].replace("@", "@" + ZERO_WIDTH_SPACE).replace("<!--", "&lt;!--")


def comment_body(repo: Repo, pr: dict, verdict: dict, safe: bool | None, note: str = "") -> str:
    headline = "✅ safe to auto-merge" if safe else "⏳ waiting for checks" if safe is None else "⚠️ needs a human"
    parts = [
        f"{MARKER} key={title_key(pr['title'])} -->",
        f"### Renovate agent: {headline} ({verdict['update_type']})",
        "**" + " ".join(clean(verdict["summary"], 200).split()) + "**",
        clean(verdict["details"], 3000),
    ]
    if pr["never_auto_merge"] and verdict["verdict"] == "safe":
        parts.append(f"> The agent judged this update safe, but {pr['never_auto_merge']}, so it needs a human.")
    if note:
        parts.append(note)
    run = os.environ.get("RUN_URL")
    watched = f"CI on `{repo.default_branch}`" + (f" and the GitImage `{repo.gitimage}` rollout" if repo.gitimage else "")
    parts.append(
        "---\n<sub>Written by an LLM reading the diff, release notes and CI logs; check before relying on it."
        + (f" [Run]({run})." if run else "")
        + f" PRs labelled `agent:safe` are merged by the agent once CI passes, one at a time; {watched}"
        " is then watched and the merge reverted if it fails. Remove the label to stop that.</sub>"
    )
    return "\n\n".join(parts)


def post_verdict(repo: Repo, number: int, body: str) -> None:
    """One verdict comment per PR: update ours if it exists, otherwise create it."""
    comments = json.loads(gh("api", f"repos/{repo.name}/issues/{number}/comments?per_page=100"))
    ours = [c for c in comments if c["user"]["login"] == repo.login and c["body"].startswith(MARKER)]
    if ours:
        gh("api", "-X", "PATCH", f"repos/{repo.name}/issues/comments/{ours[0]['id']}", "-f", f"body={body}")
    else:
        gh("api", "-X", "POST", f"repos/{repo.name}/issues/{number}/comments", "-f", f"body={body}")


def set_label(repo: Repo, number: int, safe: bool | None) -> None:
    """agent:safe, agent:needs-human, or neither (None) so the PR is triaged again."""
    wanted = {True: "agent:safe", False: "agent:needs-human"}.get(safe)
    if wanted:
        gh("api", "-X", "POST", f"repos/{repo.name}/issues/{number}/labels", "-f", f"labels[]={wanted}")
    for label in {"agent:safe", "agent:needs-human"} - {wanted}:
        # Fails with 404 when the PR does not have the label; that is fine.
        subprocess.run(["gh", "api", "-X", "DELETE", f"repos/{repo.name}/issues/{number}/labels/{label}"], capture_output=True)


def decide(repo: Repo, pr: dict, verdict: dict) -> tuple[bool | None, str, bool]:
    """Turn the model's verdict into (safe, note, fixed): applies its fixes if allowed.

    Does not trust the model: a major or a PR that must never be auto-merged needs a human
    whatever the verdict says, and fixes are checked in apply_fixes.
    """
    if verdict["update_type"] not in AUTO_MERGE_TYPES and not pr["never_auto_merge"]:
        pr["never_auto_merge"] = f"it is a {verdict['update_type']} update and only patch, minor, digest and lockfile updates are auto-merged"
    safe = verdict["verdict"] == "safe" and not pr["never_auto_merge"]
    fixes = verdict.get("fixes") or []
    # Fixes go in for safe updates, and for majors the owner approved on the dashboard (to
    # be merged by a person); never for a PR blocked for another reason.
    may_fix = fixes and (safe or (verdict["update_type"] == "major" and not any(repo.deny.search(f) for f in pr["files"])))

    if may_fix and pr["fix_attempts"] >= MAX_FIX_ATTEMPTS:
        return False, f"> The update needs another fix, but the agent already pushed {pr['fix_attempts']}; it needs a human.", False
    if may_fix and pr["ci"] == "pending":
        # A fix commit replaces the head the checks are running on: wait for them. No
        # label, so the PR is triaged again next time.
        return None, "> This update needs a change in the code. The agent will push it once the PR's checks finish.", False
    if may_fix:
        try:
            diff = apply_fixes(repo, pr, fixes)
        except (FixError, subprocess.CalledProcessError) as error:
            problem = error if isinstance(error, FixError) else one_line(error.stderr or error, 300)
            return False, f"> The update needs a change in the code, and the agent's fix could not be applied: {clean(str(problem), 500)}", False
        what = "it is merged with the update once CI passes" if safe else "CI runs on it; a person merges the update"
        return safe, f"The agent pushed this fix to the PR; {what}.\n\n```diff\n{clean(diff, 6000)}\n```", True
    if safe and pr["ci"] == "failing":
        return False, "> CI fails on this PR, and the agent found no fix it could make.", False
    return safe, "", False


def publish(repo: Repo, prs: list[dict], verdicts: list[dict]) -> list[int]:
    """Post the verdicts and push the fixes. Returns the PRs that got a fix."""
    by_number = {pr["number"]: pr for pr in prs}
    fixed = []
    for verdict in verdicts:
        pr = by_number.get(verdict["number"])
        if pr is None:
            print(f"{repo.name}#{verdict['number']}: not a selected PR, ignored")
            continue
        safe, note, got_fix = decide(repo, pr, verdict)
        if got_fix:
            fixed.append(pr["number"])
        body = comment_body(repo, pr, verdict, safe, note)
        shown = {True: "safe", False: "needs-human", None: "waiting for checks"}[safe] + (" + fix" if got_fix else "")
        short = re.sub(r"[|\r\n]+", " ", clean(verdict["summary"], 200))
        summary(f"| {repo.name}#{pr['number']} | {shown} | {verdict['update_type']} | {short} |")
        if flag("DRY_RUN"):
            print(f"===== {repo.name}#{pr['number']} =====\n{body}\n")
            continue
        post_verdict(repo, pr["number"], body)
        set_label(repo, pr["number"], safe)
    return fixed


# --- watching a merge --------------------------------------------------------------------


def kubectl(*args: str) -> dict:
    done = subprocess.run(["kubectl", "get", *args, "-o", "json"], check=True, capture_output=True, text=True)
    return json.loads(done.stdout)


def contains_commit(repo: Repo, revision: str, sha: str) -> bool:
    """Whether `revision` is `sha` or a later commit on top of it: the default branch can
    move during the watch, and the GitImage builds its head."""
    if revision == sha:
        return True
    if (revision, sha) not in repo.known_revisions:
        try:
            status = gh("api", f"repos/{repo.name}/compare/{sha}...{revision}", "--jq", ".status").strip()
        except subprocess.CalledProcessError:
            return False  # GitHub unreachable or an unknown commit: ask again next time
        repo.known_revisions[(revision, sha)] = status in ("identical", "ahead")
    return repo.known_revisions[(revision, sha)]


def commit_ci(repo: Repo, sha: str) -> tuple[str, str]:
    """(state, detail) of the checks on a commit: passing, failing, pending or none."""
    runs = json.loads(gh("api", f"repos/{repo.name}/commits/{sha}/check-runs?per_page=100"))["check_runs"]
    statuses = json.loads(gh("api", f"repos/{repo.name}/commits/{sha}/status"))["statuses"]
    failed = [r["name"] for r in runs if r["status"] == "completed" and r["conclusion"] not in ("success", "skipped", "neutral")]
    failed += [s["context"] for s in statuses if s["state"] in ("failure", "error")]
    if failed:
        return "failing", ", ".join(failed)
    pending = [r["name"] for r in runs if r["status"] != "completed"] + [s["context"] for s in statuses if s["state"] == "pending"]
    if pending:
        return "pending", ", ".join(pending)
    return ("passing", "") if runs or statuses else ("none", "")


def bound_workloads(namespace: str, name: str) -> list[dict]:
    """Deployments and StatefulSets whose pod template takes an image from this GitImage
    (the `gitimage.dev/image.<container>` annotation the GitImage roller reads)."""
    found = []
    for kind in ("deployments", "statefulsets"):
        for item in kubectl(kind, "-n", namespace)["items"]:
            annotations = item["spec"]["template"]["metadata"].get("annotations") or {}
            containers = [k.removeprefix("gitimage.dev/image.") for k, v in annotations.items() if k.startswith("gitimage.dev/image.") and v == name]
            if containers:
                found.append({"kind": kind, "item": item, "containers": containers})
    return found


def rollout_problem(workload: dict, revision: str) -> str:
    """'' when the workload runs `revision` everywhere and all its replicas are available,
    else what is still missing."""
    item = workload["item"]
    name = f"{workload['kind'][:-1]}/{item['metadata']['name']}"
    annotations = item["spec"]["template"]["metadata"].get("annotations") or {}
    for container in workload["containers"]:
        if annotations.get(f"gitimage.dev/revision.{container}") != revision:
            return f"{name} not at {revision[:8]} yet"
    status, want = item.get("status", {}), item["spec"].get("replicas", 1)
    if status.get("observedGeneration", 0) < item["metadata"]["generation"]:
        return f"{name} rollout not observed yet"
    if status.get("updatedReplicas", 0) < want or status.get("availableReplicas", 0) < want or status.get("replicas", 0) > want:
        return f"{name} rolling out ({status.get('availableReplicas', 0)}/{want} available)"
    return ""


def restarts(namespace: str, workloads: list[dict]) -> dict[str, int]:
    """Container restart counts of the workloads' pods."""
    counts = {}
    for workload in workloads:
        selector = workload["item"]["spec"]["selector"].get("matchLabels") or {}
        query = ",".join(f"{k}={v}" for k, v in selector.items())
        for pod in kubectl("pods", "-n", namespace, "-l", query)["items"]:
            for c in pod.get("status", {}).get("containerStatuses") or []:
                counts[f"{pod['metadata']['name']}/{c['name']}"] = c.get("restartCount", 0)
    return counts


def gitimage_state(repo: Repo, sha: str) -> tuple[str, str, list[dict], str]:
    """(state, detail, workloads, revision) of the GitImage for a merged commit: rolled out,
    failing or pending."""
    namespace, name = repo.gitimage.split("/")
    gi = kubectl("gitimages.gitimage.dev", "-n", namespace, name)
    status = gi.get("status", {})
    builds = [b for b in status.get("builds") or [] if contains_commit(repo, b.get("revision", ""), sha)]
    if not builds:
        return "pending", f"GitImage {name} has not built {sha[:8]} yet", [], ""
    newest = builds[0]  # newest first
    if newest.get("outcome") == "Failed":
        return "failing", f"GitImage {name} failed to build {newest['revision'][:8]}", [], ""
    if newest.get("outcome") not in ("Built", "Reused") or status.get("revision") != newest["revision"]:
        return "pending", f"GitImage {name} building {newest['revision'][:8]}", [], ""
    workloads = bound_workloads(namespace, name)
    for workload in workloads:
        problem = rollout_problem(workload, newest["revision"])
        if problem:
            return "pending", problem, workloads, newest["revision"]
    return "rolled out", "", workloads, newest["revision"]


def deploy_problem(repo: Repo) -> str:
    """Why merges in this repo cannot be watched right now (its app is already unhealthy,
    so a broken merge would not show), or '' if they can."""
    if not repo.gitimage:
        return ""
    namespace, name = repo.gitimage.split("/")
    try:
        gi = kubectl("gitimages.gitimage.dev", "-n", namespace, name)
    except subprocess.CalledProcessError as error:
        return f"GitImage {repo.gitimage} cannot be read: {one_line(error.stderr, 200)}"
    conditions = {c["type"]: c["status"] for c in gi.get("status", {}).get("conditions", [])}
    if conditions.get("Ready") != "True" or conditions.get("Building") == "True":
        return f"GitImage {repo.gitimage} is not idle and Ready"
    revision = gi["status"].get("revision", "")
    for workload in bound_workloads(namespace, name):
        problem = rollout_problem(workload, revision)
        if problem:
            return f"the app is not healthy before the merge: {problem}"
    return ""


def wait_settled(repo: Repo, sha: str) -> str:
    """Wait until CI on the merged commit passed and (with a GitImage) the commit is built,
    rolled out and stayed up without restarts for SOAK seconds. Returns '' on success,
    otherwise what is wrong."""
    start = time.monotonic()
    deadline = start + repo.settle
    soak_from, baseline = None, {}
    while True:
        time.sleep(POLL)
        try:
            ci, ci_detail = commit_ci(repo, sha)
            if ci == "none" and time.monotonic() - start < NO_CI_GRACE:
                ci, ci_detail = "pending", "no checks on the merged commit yet"
            if ci == "failing":
                return f"CI failed on {sha[:8]}: {ci_detail}"
            state, detail, workloads = "rolled out", "", []
            if repo.gitimage:
                state, detail, workloads, _ = gitimage_state(repo, sha)
                if state == "failing":
                    return detail
            waiting = [d for d in (ci_detail if ci == "pending" else "", detail) if d]
            if not waiting and repo.gitimage:
                now = restarts(repo.gitimage.split("/")[0], workloads)
                if soak_from is None:
                    soak_from, baseline = time.monotonic(), now
                elif crashed := [p for p, n in now.items() if n > baseline.get(p, n)]:
                    return f"containers restarted after the rollout: {', '.join(crashed)}"
        except (subprocess.CalledProcessError, KeyError, json.JSONDecodeError) as error:
            # The update is already merged: a failed look must not skip the revert. Count
            # it as not settled and keep trying until the deadline.
            waiting = [f"could not read the state ({type(error).__name__})"]
        if waiting:
            soak_from = None
            print(f"  waiting for {', '.join(waiting)}", flush=True)
            if time.monotonic() > deadline:
                return "not settled in time: " + ", ".join(waiting)
            continue
        if not repo.gitimage or time.monotonic() - soak_from >= SOAK:
            return ""


def cluster_problem() -> str:
    """Why nothing should be merged right now, or '' if the cluster is fine."""
    for node in kubectl("nodes")["items"]:
        ready = [c["status"] for c in node["status"]["conditions"] if c["type"] == "Ready"]
        if ready != ["True"]:
            return f"node {node['metadata']['name']} is not Ready"
    return ""


# --- merging -----------------------------------------------------------------------------


def comment(repo: Repo, number: int, body: str) -> None:
    gh("api", "-X", "POST", f"repos/{repo.name}/issues/{number}/comments", "-f", f"body={body}")


def revert(repo: Repo, sha: str) -> None:
    """Push a revert of `sha` straight to the default branch."""
    tree = repo.work / "revert"
    if tree.exists():
        shutil.rmtree(tree)
    git("clone", "--quiet", "--depth", "50", "--branch", repo.default_branch, repo.url, str(tree))
    git("revert", "--no-edit", sha, cwd=tree)
    git("push", repo.url, f"HEAD:{repo.default_branch}", cwd=tree, push=True)


def merge_commit(repo: Repo, number: int) -> str:
    """The commit a just-merged PR landed as. Retried: without it the rollout cannot be
    watched or reverted."""
    for _ in range(10):
        try:
            return json.loads(gh("pr", "view", str(number), "--repo", repo.name, "--json", "mergeCommit"))["mergeCommit"]["oid"]
        except (subprocess.CalledProcessError, TypeError, KeyError):
            time.sleep(POLL)
    sys.exit(f"{repo.name}#{number} was merged but its merge commit could not be read: check it and revert by hand if needed")


def merge_one(repo: Repo, pr: dict) -> bool:
    """Merge one PR and see it through. Returns False if no further PR should be merged."""
    number = pr["number"]
    problem = cluster_problem()
    if problem:
        summary(f"- {repo.name}#{number} not merged, and nothing after it: {problem}")
        return False
    problem = deploy_problem(repo)
    if problem:
        summary(f"- {repo.name}#{number} not merged, nor anything else in this repo: {problem}")
        return False
    watched = f"CI on {repo.default_branch}" + (f", GitImage {repo.gitimage}" if repo.gitimage else "")
    if flag("DRY_RUN"):
        summary(f"- {repo.name}#{number} would be merged, watching {watched}")
        return True

    try:
        gh("pr", "merge", str(number), "--repo", repo.name, "--squash", "--match-head-commit", pr["headRefOid"])
    except subprocess.CalledProcessError as error:
        summary(f"- {repo.name}#{number} not merged: {one_line(error.stderr, 300)}")
        return True
    # Merged: from here on every path either confirms the rollout or reverts it.
    sha = merge_commit(repo, number)
    print(f"{repo.name}#{number} merged as {sha}, watching {watched}", flush=True)

    problem = wait_settled(repo, sha)
    if not problem:
        soaked = f", and the rollout stayed up for {SOAK // 60} minutes" if repo.gitimage else ""
        summary(f"- {repo.name}#{number} merged ({sha[:8]}): {watched} fine{soaked}")
        comment(repo, number, f"Merged by the Renovate agent as {sha}. {watched}: passed{soaked}.")
        return True

    summary(f"- {repo.name}#{number} merged ({sha[:8]}) and **reverted**: {problem}")
    try:
        revert(repo, sha)
    except subprocess.CalledProcessError as error:
        sys.exit(f"{repo.name}#{number} ({sha}) is broken ({problem}) and the revert failed: "
                 f"{one_line(error.stderr or error, 300)}. Revert it by hand.")  # fmt: skip
    # The label is what stops this update from being merged again: set it before anything else.
    gh("api", "-X", "POST", f"repos/{repo.name}/issues/{number}/labels", "-f", "labels[]=agent:reverted")
    comment(repo, number, f"The Renovate agent merged this as {sha} and then **reverted it**: {problem}.\n\n"
                          "The same update will not be auto-merged again; it needs a human.")  # fmt: skip
    sys.exit(f"{repo.name}#{number} was reverted: {problem}")


def merge_candidates(repo: Repo) -> list[dict]:
    """Open PRs with green CI that carry a safe verdict for their current title."""
    reverted = reverted_titles(repo)
    return [
        pr
        for pr in list_prs(repo)
        if ci_state(pr) == "passing"
        and has_verdict(repo, pr)
        and "agent:safe" in labels(pr)
        and not never_auto_merge(repo, pr, reverted)
        and pr["mergeable"] != "CONFLICTING"
    ]


def merge_safe_prs(repo: Repo, budget: int) -> int:
    """Merge the repo's safe PRs one at a time; returns how many were merged. The list is
    read again before every merge, so removing agent:safe meanwhile still works."""
    handled = set()
    while len(handled) < min(budget, MAX_MERGES_PER_REPO):
        if time.monotonic() - STARTED > MERGE_WINDOW:
            summary(f"- {repo.name}: merge window ({MERGE_WINDOW // 3600} h) is over, the rest waits for the next run")
            break
        candidates = [pr for pr in merge_candidates(repo) if pr["number"] not in handled]
        if not candidates:
            break
        handled.add(candidates[0]["number"])
        if not merge_one(repo, candidates[0]):
            break
    return len(handled)


def wait_for_checks(repo: Repo, numbers: list[int]) -> None:
    """Give CI on freshly pushed fixes a chance to finish, so they can be merged in this run."""
    deadline = time.monotonic() + CI_WAIT
    while numbers and not flag("DRY_RUN") and time.monotonic() < deadline:
        time.sleep(POLL * 2)
        pending = [pr["number"] for pr in list_prs(repo) if pr["number"] in numbers and ci_state(pr) == "pending"]
        if not pending:
            return
        print(f"  waiting for CI on {', '.join(f'{repo.name}#{n}' for n in pending)}", flush=True)


def handle(repo: Repo, merge_budget: int) -> int:
    """Triage one repo's PRs, then merge its safe ones. Returns how many were merged."""
    checkout_repo(repo)
    prs = select_prs(repo)
    summary(f"\n### {repo.name}: {len(prs)} PRs to triage")
    if prs:
        summary("| PR | Verdict | Type | Summary |\n|---|---|---|---|")
    fixed = []
    for start in range(0, len(prs), BATCH):
        batch = prs[start : start + BATCH]
        for pr in batch:
            fetch_pr(repo, pr)
        fixed += publish(repo, batch, run_claude(repo, batch))
    wait_for_checks(repo, fixed)
    return merge_safe_prs(repo, merge_budget)


def main() -> None:
    login = gh("api", "user", "--jq", ".login").strip()
    entries = yaml.safe_load((HERE / "repos.yaml").read_text())["repos"]
    only = os.environ.get("ONLY_REPO", "")
    repos = [Repo(entry, login) for entry in entries if not only or entry["repo"].lower() == only.lower()]
    if not repos:
        sys.exit(f"no repo in repos.yaml matches ONLY_REPO={only}")
    WORK.mkdir(exist_ok=True)
    merged = 0
    for repo in repos:
        try:
            merged += handle(repo, MAX_MERGES - merged)
        except subprocess.CalledProcessError as error:
            # One repo's trouble (a vanished branch, an API error) must not stop the others.
            # A failure after a merge never gets here: merge_one exits or reverts itself.
            summary(f"- {repo.name}: skipped after an error: {one_line(error.stderr or error, 400)}")


if __name__ == "__main__":
    main()
